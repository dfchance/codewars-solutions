# Kata: String Ends With? 
# Difficulty: 7 kyu
# URL: https://www.codewars.com/kata/51f2d1cafc9c0f745c00037d
#
# Description: 
# Determine if the first string passed ends in the second string passed.
#
# Approach:
# Use the string function endswith(str). 

def solution(text, ending):
    return text.endswith(ending)