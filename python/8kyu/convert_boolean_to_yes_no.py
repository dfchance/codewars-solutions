# Kata: Convert Boolean Values to String 'Yes' or 'No'
# Difficulty: 8 kyu
# URL: https://www.codewars.com/kata/53369039d7ab3ac506000467/
# 
# Description: 
# Complete a function that returns 'Yes' for True and 'No' for False.
#
# Approach:
# Use an if/else statement in the return statement.  

def bool_to_word(boolean):
    return 'Yes' if boolean==True else 'No'